/// 隣接駅ペアに対応する実効最高速度(km/h)を返す。エントリが無ければ `None`。
/// 駅の並び順(進行方向)は問わない。
pub fn segment_speed_override_kmh(
    line_cd: i32,
    station_cd_a: i32,
    station_cd_b: i32,
) -> Option<f64> {
    let (lo, hi) = if station_cd_a <= station_cd_b {
        (station_cd_a, station_cd_b)
    } else {
        (station_cd_b, station_cd_a)
    };
    SEGMENT_SPEED_OVERRIDES
        .binary_search_by(|&(lc, a, b, _)| (lc, a, b).cmp(&(line_cd, lo, hi)))
        .ok()
        .map(|i| SEGMENT_SPEED_OVERRIDES[i].3)
}

/// 駅間別較正を適用してよい種別か(速度倍率 1.0 の各停系のみ)。
///
/// `arrival_estimation` と `GetTrainRoute` の速度プロファイルの両方から参照し、
/// 適用条件を一箇所で管理する。
pub fn segment_override_applies_to_kind(kind: Option<i32>) -> bool {
    !matches!(
        kind.and_then(|v| TrainTypeKind::try_from(v).ok()),
        Some(TrainTypeKind::Express)
            | Some(TrainTypeKind::LimitedExpress)
            | Some(TrainTypeKind::HighSpeedRapid)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_for_binary_search() {
        // 二分探索の前提: 生成テーブルが (line_cd, cd小, cd大) 昇順であること。
        // スクリプトはソート済みで出力するが、手動編集事故を回帰検知する。
        assert!(SEGMENT_SPEED_OVERRIDES
            .windows(2)
            .all(|w| (w[0].0, w[0].1, w[0].2) < (w[1].0, w[1].1, w[1].2)));
        // ペアは (小, 大) 正規化済みであること。
        assert!(SEGMENT_SPEED_OVERRIDES.iter().all(|&(_, a, b, _)| a < b));
    }

    #[test]
    fn lookup_is_order_insensitive() {
        // エントリの有無は生成結果に依存するため、両方向で同じ結果になることだけを
        // 全エントリに対して検証する。
        for &(lc, a, b, v) in SEGMENT_SPEED_OVERRIDES {
            assert_eq!(segment_speed_override_kmh(lc, a, b), Some(v));
            assert_eq!(segment_speed_override_kmh(lc, b, a), Some(v));
        }
        assert_eq!(segment_speed_override_kmh(-1, 1, 2), None);
    }

    #[test]
    fn express_kinds_are_excluded() {
        assert!(segment_override_applies_to_kind(None));
        assert!(segment_override_applies_to_kind(Some(
            TrainTypeKind::Default as i32
        )));
        assert!(segment_override_applies_to_kind(Some(
            TrainTypeKind::Rapid as i32
        )));
        assert!(!segment_override_applies_to_kind(Some(
            TrainTypeKind::Express as i32
        )));
        assert!(!segment_override_applies_to_kind(Some(
            TrainTypeKind::LimitedExpress as i32
        )));
        assert!(!segment_override_applies_to_kind(Some(
            TrainTypeKind::HighSpeedRapid as i32
        )));
    }
}
