//! 隣接駅間ごとの実効速度の較正テーブル(駅間別較正)。
//!
//! 路線 × 種別単位の較正(`speed_table`)は路線内で一様な実効速度を仮定するが、
//! 実路線には区間ごとの速度差がある(都営大江戸線の環状部南側 月島〜赤羽橋は
//! 河川横断の急勾配・急曲線で放射部より 2〜3 割遅い、など)。路線一様速度では
//! この残差を原理的に解消できないため、公開 GTFS 時刻表から隣接駅ペア単位で
//! フィットした実効速度をここで上書きする。
//!
//! 生成は `scripts/compute_speed_table.py --apply`(路線単位テーブルと同時生成)。
//! 駅間の純走行時間(次駅の到着時刻が別記録されていれば「出発 → 次駅到着」、
//! 無ければ「出発 → 次駅出発 − モデル停車時分」)を複数本の平均でデクオンタイズし、
//! `arrival_estimation` の運動学モデルを再現する実効最高速度を二分探索で求め、
//! 路線単位の較正値から ±5% 以上乖離したペアだけを出力する(乖離が小さい
//! ペアは路線値で十分)。時刻データが無い駅間は路線単位の較正値のままになる。
//!
//! 適用条件:
//! - 各駅停車と同速の種別(速度倍率 1.0: Default/Branch/Rapid/CommuterRapid)のみ。
//!   急行・特急(倍率 > 1.0)は待避線前提の速達ダイヤであり、各停の実ダイヤから
//!   フィットした駅間速度で引き下げない。
//! - バスには適用しない(道路交通の駅間時間は GTFS 由来の路線単位較正で扱う)。

